def fix_years():
    """修正论文年份"""
    # 读取数据
    with open(DATA_FILE, 'r', encoding='utf-8') as f:
        data = json.load(f)

    print("修正论文年份...")
    print("=" * 80)

    fixed_count = 0
    for r in data:
        filename = r['metadata']['filename']

        # 尝试从文件名中提取编号
        for key, year in YEAR_MAPPING.items():
            if key in filename:
                old_year = r['metadata'].get('year', 'N/A')
                r['metadata']['year'] = str(year)
                if old_year != str(year):
                    print(f"  {r['index']:3d}. {filename[:40]:40s} {old_year:4s} -> {year}")
                    fixed_count += 1
                break

    # 保存修正后的数据
    with open(DATA_FILE, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print("=" * 80)
    print(f"修正完成: {fixed_count} 篇论文的年份已修正")

    # 统计修正后的年份分布
    year_counts = {}
    for r in data:
        year = r['metadata'].get('year', 'N/A')
        year_counts[year] = year_counts.get(year, 0) + 1

    print("\n修正后的年份分布:")
    for y in sorted(year_counts.keys()):
        print(f"  {y}: {year_counts[y]} 篇")

if __name__ == "__main__":
    fix_years()
